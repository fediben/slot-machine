import test from "node:test";
import assert from "node:assert/strict";
import {createHmac,createHash,randomUUID} from "node:crypto";
const base=process.env.SLOT_URL||"http://127.0.0.1:8787";
const sha=s=>createHash("sha256").update(s).digest("hex");
const api=async(path,method="GET",body,headers={})=>{
 const r=await fetch(base+path,{method,headers:{...headers,...(body===undefined?{}:{"Content-Type":"application/json"})},body:body===undefined?undefined:JSON.stringify(body)});
 return {status:r.status,data:await r.json()};
};
const admin=(path,method="GET",body)=>api("/api/admin"+path,method,body,{Authorization:"Bearer unit-test-admin-token-123"});
const call=(m,path,method="GET",body,nonce=randomUUID().replace(/-/g,""))=>{
 const timestamp=String(Date.now()),raw=body===undefined?"":JSON.stringify(body);
 const signature=createHmac("sha256",m.key).update([timestamp,nonce,method,path,sha(raw)].join("\n")).digest("hex");
 return api(path,method,body,{"X-Machine-Id":m.id,"X-Machine-Timestamp":timestamp,"X-Machine-Nonce":nonce,"X-Machine-Signature":signature});
};
test("D1 event lifecycle, security, replay, stop acknowledgement", {timeout:90000}, async()=>{
 const unique="kiosk-"+randomUUID().slice(0,8);
 const ev=await admin("/events","POST",{name:"Event Test Kiosk",slug:unique,starting_credits:500,max_sessions_per_profile:1});
 assert.equal(ev.status,201,JSON.stringify(ev));
 const id=ev.data.id;
 const provision=await admin("/machines","POST",{event_id:id,name:"Test Kiosk 01"});
 assert.equal(provision.status,201,JSON.stringify(provision));
 const m={id:provision.data.id,key:Buffer.from(provision.data.machine_key,"base64url")};
 assert.equal(m.key.length,32);
 assert.equal((await call(m,"/api/machine/state")).status,200);
 const nonce=randomUUID().replace(/-/g,"");
 assert.equal((await call(m,"/api/machine/state","GET",undefined,nonce)).status,200);
 assert.equal((await call(m,"/api/machine/state","GET",undefined,nonce)).status,409);
 const link=await call(m,"/api/machine/checkins","POST",{});
 assert.equal(link.status,200,JSON.stringify(link));
 const token=link.data.join_url.split("/").pop();
 assert.equal((await api("/api/join/"+token,"POST",{name:"Alice",pin:"bad"})).status,400);
 const joined=await api("/api/join/"+token,"POST",{name:"Alice",pin:"542897"});
 assert.equal(joined.status,200,JSON.stringify(joined));
 assert.equal((await api("/api/join/"+token)).status,410);
 const state=await call(m,"/api/machine/state");
 const sid=state.data.session.id;assert.equal(state.data.session.credits,500);
 const spin=await call(m,"/api/machine/spins","POST",{session_id:sid,cost:50});
 assert.equal(spin.status,200,JSON.stringify(spin));
 assert.equal((await call(m,"/api/machine/spins","POST",{session_id:sid,cost:50})).status,409);
 const ticket=spin.data.spin_token;
 const played_at=Date.now(),score={session_id:sid,spin_token:ticket,award:150,played_at,client_result_hash:sha(ticket+":"+sid+":150:"+played_at)};
 assert.equal((await call(m,"/api/machine/scores","POST",{...score,client_result_hash:"0".repeat(64)})).status,422);
 const ok=await call(m,"/api/machine/scores","POST",score);
 assert.equal(ok.status,200,JSON.stringify(ok));assert.equal(ok.data.session.credits,600);
 assert.equal((await call(m,"/api/machine/scores","POST",score)).data.duplicate,true);
 assert.equal((await call(m,"/api/machine/scores","POST",{...score,award:155})).status,409);
 const board=await api("/api/events/"+unique+"/leaderboard");
 assert.equal(board.status,200);assert.equal(board.data.leaderboard[0].points,150);
 assert.equal((await admin("/settings","PATCH",{event_id:id,key:"leaderboard_title",value:"Geneva Kiosk"})).status,200);
 assert.equal((await admin("/settings?event_id="+id)).data.settings.leaderboard_title,"Geneva Kiosk");
 assert.equal((await admin("/scores?event_id="+id)).data.scores.length,1);
 assert.equal((await admin("/leaderboard?event_id="+id)).data.standings.length,1);
 const disabled=await admin("/machines/"+m.id,"PATCH",{enabled:false});assert.equal(disabled.status,200);
 const disabledState=await call(m,"/api/machine/state");
 assert.equal(disabledState.data.machine.enabled,false);
 assert.equal((await call(m,"/api/machine/checkins","POST",{})).status,423);
 assert.equal((await call(m,"/api/machine/spins","POST",{session_id:sid,cost:50})).status,423);
 const seq=disabledState.data.machine.command_seq;
 assert.equal((await call(m,"/api/machine/ack","POST",{command_seq:seq})).status,200);
 assert.equal((await call(m,"/api/machine/state")).data.machine.ack_seq,seq);
 assert.equal((await call(m,"/api/machine/end","POST",{session_id:sid})).status,200);
 assert.equal((await admin("/machines/"+m.id,"PATCH",{enabled:true})).status,200);
 const next=await call(m,"/api/machine/checkins","POST",{});
 assert.equal(next.status,200);
 const again=await api("/api/join/"+next.data.join_url.split("/").pop(),"POST",{name:"Alice",pin:"542897"});
 assert.equal(again.status,409,JSON.stringify(again));
 assert.equal((await admin("/events/"+id,"PATCH",{state:"closed"})).status,200);
 assert.equal((await call(m,"/api/machine/checkins","POST",{})).status,423);
});
